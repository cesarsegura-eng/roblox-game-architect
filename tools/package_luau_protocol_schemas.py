"""Generate the Studio plugin's Luau schema registry from protocol v1 JSON files."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_ROOT = ROOT / "packages" / "protocol" / "schemas" / "v1"
OUTPUT = ROOT / "apps" / "studio-plugin" / "src" / "Protocol" / "Schemas.lua"


def _luau(value: object, depth: int = 0) -> str:
    indent = "\t" * depth
    child_indent = "\t" * (depth + 1)
    if value is None:
        raise ValueError("Protocol schemas cannot contain null")
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        if not value:
            return "{}"
        entries = [f"{child_indent}{_luau(item, depth + 1)}" for item in value]
        return "{\n" + ",\n".join(entries) + f"\n{indent}}}"
    if isinstance(value, dict):
        if not all(isinstance(key, str) for key in value):
            raise ValueError("Protocol schema object keys must be strings")
        if not value:
            return "{}"
        entries = [
            f"{child_indent}[{json.dumps(key, ensure_ascii=False)}] = {_luau(item, depth + 1)}"
            for key, item in sorted(value.items())
        ]
        return "{\n" + ",\n".join(entries) + f"\n{indent}}}"
    raise ValueError(f"Unsupported protocol schema value: {type(value).__name__}")


def render() -> str:
    schemas = {
        path.relative_to(SCHEMA_ROOT).as_posix(): json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(SCHEMA_ROOT.rglob("*.json"))
        if path.name != "version.json"
    }
    version = json.loads((SCHEMA_ROOT / "version.json").read_text(encoding="utf-8"))
    registry = {"types": version["types"], "schemas": schemas}
    return (
        "-- Generated by tools/package_luau_protocol_schemas.py; do not edit by hand.\n"
        "return " + _luau(registry) + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the generated module is stale"
    )
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            print(
                f"{OUTPUT.relative_to(ROOT)} is stale; run "
                "python tools/package_luau_protocol_schemas.py"
            )
            return 1
        print("Luau protocol schemas are synchronized.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
